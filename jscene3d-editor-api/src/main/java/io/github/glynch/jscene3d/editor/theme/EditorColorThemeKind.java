package io.github.glynch.jscene3d.editor.theme;

/** Broad luminance and contrast family used by toolkit theme adapters. */
public enum EditorColorThemeKind {
    /** Dark background and ordinary contrast. */
    DARK,
    /** Light background and ordinary contrast. */
    LIGHT,
    /** Dark background and enhanced contrast. */
    HIGH_CONTRAST_DARK,
    /** Light background and enhanced contrast. */
    HIGH_CONTRAST_LIGHT
}
